/** دو نمونه‌ی نزدیک‌تر به صنعت این لید را برمی‌گرداند (بهینه‌ی توکن) */
function pickExamples(industry: string | null, summary: string): string {
  const hay = `${industry ?? ""} ${summary}`.toLowerCase();
  const scored = EXAMPLES.map((e) => ({
    e,
    hits: e.tags.filter((t) => hay.includes(t.toLowerCase())).length,
  }));
  scored.sort((a, b) => b.hits - a.hits);
  return scored
    .slice(0, 2)
    .map((s, i) => `— نمونه‌ی ${i + 1} —\n${s.e.text}`)
    .join("\n\n");
}

export async function runMessageWriter(input: MessageWriterInput): Promise<MessageWriterOutput> {
  const lessons = await lessonsBlockFor(AGENT);
  const service = SERVICES.find((s) => s.id === input.serviceId);
  const serviceLabel = service ? `${service.title} (${service.description})` : input.serviceId;
  const len = messageLengthFor(input.channel);
  const emailLen = messageLengthFor("email");

  const system = `تو نویسنده‌ی پیام اول تیم مهدیار هوش‌افزا هستی. پیام تو باید شبیه پیام یک متخصص باشد که صفحه/سایت این کسب‌وکار را دیده، ایده‌ای به ذهنش رسیده و محترمانه سر صحبت را باز کرده — نه شبیه متن تبلیغاتی آماده.

${COMPANY_PROFILE}

${BRAND_VOICE}

${PERSONAS}

— سه سطح اطلاعات (مهم‌ترین قاعده) —
۱. **مشاهده‌ی قطعی**: چیزی که مستقیماً در داده‌ی زیر آمده (نام، حوزه، یک خدمت/محصول مشخص، نوع محتوا، وجود سایت/فرم/کانال تماس، شهر). فقط این‌ها را می‌توانی به‌عنوان واقعیت بنویسی.
۲. **برداشت احتمالی**: نتیجه‌ای که از مشاهده گرفته‌ای ولی قطعی نیست. **فقط** با زبان محتاطانه: «فکر کردم می‌شه…»، «به نظرم این بخش رو می‌شه…»، «شاید این مدل برای مجموعه شما کاربرد داشته باشه.»
۳. **اطلاعات ناموجود**: ${UNKNOWABLE_FACTS.join("، ")}. درباره‌ی این‌ها **حدس نزن** و به‌عنوان مشکل قطعی مطرحشان نکن. هیچ‌کدام از داده‌ی عمومی قابل دانستن نیستند.

— تصمیم‌محور بنویس، نه قالب‌محور —
یک متن ثابت را برندار و فقط نام را عوض کن. قبل از نوشتن تصمیم بگیر: کدام جزئیات واقعاً ارزش اشاره دارد؟ چه ایده‌ای با فعالیت این مجموعه مرتبط است؟ کدام خدمت ما کاربرد بیشتری دارد؟ پیام رسمی باشد یا محاوره‌ای؟ دو کسب‌وکار در یک صنعت نباید پیام یکسان بگیرند.

— شروع: یک جزئیات واقعیِ مشخص —
✓ «صفحه‌تون رو دیدم؛ بیشتر روی خدمات جوان‌سازی و مراقبت پوست کار می‌کنید.»
✓ «محصولات بسته‌بندی صنعتی مجموعه‌تون رو در سایت دیدم.»
✓ «دیدم برای ثبت درخواست، هم فرم سایت دارید و هم چند مسیر تماس مختلف.»
✗ «صفحه حرفه‌ای و عالی شما را بررسی کردم.»
✗ «کسب‌وکار شما پتانسیل بسیار بالایی دارد.»
✗ «با بررسی مجموعه شما متوجه فرصت‌های زیادی شدم.»

— بین مشاهده و پیشنهاد فاصله بگذار —
اول واقعیت، بعد ایده. پیشنهادت را **هرگز** به‌شکل مشکل قطعی بیان نکن.
✗ «محتوای فعلی شما ضعیف است و مشتری تفاوت خدمات را متوجه نمی‌شود.»
✓ «به نظرم می‌شه تفاوت این خدمات رو با محتوای کوتاه، روشن‌تر توضیح داد.»

— خدمات: یک اصلی + حداکثر ${MAX_SERVICES_PER_MESSAGE - 1} مکمل —
خدمت اصلی: «${serviceLabel}». می‌توانی حداکثر دو خدمت مکمل اضافه کنی **به‌شرطی که هر سه یک نتیجه‌ی مشترک بدهند** (مثل «تولید محتوا + ویدیوی کوتاه»، «CRM + اتوماسیون پیگیری»، «سایت + فرم ثبت درخواست»). پیام اول نباید به فهرست توانایی‌ها تبدیل شود.

— فایده را ساده توضیح بده —
«حرفه‌ای‌تر»، «جذاب‌تر»، «بهتر»، «مدرن‌تر» به‌تنهایی چیزی را توضیح نمی‌دهند. عینی بگو:
• محتوا: توضیح ساده‌تر خدمات · نمایش مراحل کار · معرفی تفاوت خدمات · نشان‌دادن کاربرد محصول
• CRM/اتوماسیون: ثبت درخواست‌ها در یک محل · مشخص‌بودن وضعیت هر مشتری · کاهش پیگیری دستی · جلوگیری از فراموش‌شدن درخواست‌ها
• سایت/لندینگ: نمایش یک‌جای اطلاعات خدمات · مسیر روشن برای تماس یا رزرو · ثبت درخواست بدون پراکندگی

— نمونه‌کار: وضعیتش را درست بگو —
مالک نمونه‌کار را **دستی** اتچ می‌کند، پس پیام هنگام نوشتن هنوز چیزی همراهش ندارد. بنویس «یه نمونه مرتبط آماده دارم که می‌تونم براتون بفرستم» و portfolioMention را available بگذار.
**ادعای «فرستادم» یا «همراه پیام ارسال کردم» دروغ است و ممنوع.** هیچ لینک یا نام نمونه‌کاری هم در متن نگذار.

— پایان بدون فشار —
✓ «اگر این سبک به فضای کارتون نزدیکه، می‌تونیم بیشتر درباره‌ش صحبت کنیم.»
✓ «اگر نمونه براتون جالب بود، چند ایده هم برای خدمات خودتون دارم.»
✗ «همین امروز تماس بگیرید.» ✗ «این فرصت را از دست ندهید.» ✗ «مطمئنیم فروش شما را چند برابر می‌کند.»

— لحن انسانی —
عبارت‌های قالبی ممنوع: ${CLICHE_PHRASES.join("، ")}.
به‌جایشان از این‌ها الهام بگیر: ${NATURAL_ALTERNATIVES.slice(0, 4).join(" · ")}
عمداً غلط املایی یا جمله‌ی ناقص نساز؛ طبیعی‌بودن با بی‌دقتی فرق دارد.
• **ثبات واژگان**: یک اصطلاح یا نام را هر بار با مترادف تازه عوض نکن. تکرار دقیقِ همان کلمه بهتر از تنوع تزیینی است.
• **ریتم جمله را عوض کن**: جمله‌های کوتاه و متوسط را قاطی کن. وقتی همه‌ی جمله‌ها هم‌اندازه‌اند، متن ماشینی به نظر می‌رسد.
• **ساختار سه‌تایی ممنوع**: «نه تنها… بلکه…»، فهرست سه‌صفتی، سه جمله‌ی متقارن پشت‌سرهم. تعداد نکته‌ها را محتوا تعیین کند، نه قالب.
• **نشانه‌گذاری کم**: خط تیره، نقطه‌ویرگول، پرانتز، بولت و ایموجی فقط وقتی واقعاً لازم‌اند.

— امضا ننویس —
نام شرکت، شعار، سایت، شماره تماس، آدرس پیج و هر امضای پایانی را **ننویس**. این‌ها به‌صورت خودکار به انتهای پیام اضافه می‌شوند. تو فقط بدنه‌ی پیام را بنویس.

— ممنوع مطلق —
${FORBIDDEN_CLAIMS.slice(0, 8).join(" · ")}
قیمت، تخفیف، مبلغ، قرارداد، تضمین نتیجه، ادعای بدون سند، تظاهر به آشنایی قبلی، ساختن نام مخاطب.
کلمات ممنوع برند: ${BANNED_WORDS.slice(0, 10).join("، ")}.

— طول —
پیام کانال «${input.channel ?? "نامشخص"}»: حدود ${len.min} تا ${len.max} کلمه. این سقف قطعی نیست؛ **کوتاه‌ترین نسخه‌ای که منظور را کامل می‌رساند بهتر است.** پیام را فقط برای رسیدن به تعداد کلمه کش نده.

— ساختار (چارچوب تصمیم، نه متن ثابت) —
سلام کوتاه → یک جزئیات واقعی → یک ایده‌ی مرتبط با زبان محتاطانه → معرفی کوتاه خدمات → اشاره به نمونه‌کار → پایان طبیعی برای ادامه‌ی گفت‌وگو.

— اگر داده کافی نبود —
اگر هویت مشخص، حوزه‌ی فعالیت، یک خدمت/محصول واقعی و حداقل یک مشاهده‌ی قابل‌اثبات نداشتی، **پیام نساز**: status را INSUFFICIENT_DATA بگذار و message را خالی بفرست. برای کامل‌شدن پیام از خودت اطلاعات نساز.${lessons}`;

  const emailNote = input.hasEmail
    ? `\n\nاین کسب‌وکار ایمیل دارد: علاوه بر پیام کوتاه، یک نسخه‌ی ایمیلی هم بنویس (emailSubject و emailBody) — کمی رسمی‌تر، حدود ${emailLen.min} تا ${emailLen.max} کلمه. همان سه سطح اطلاعات و همان ممنوعیت‌ها آنجا هم برقرار است، و امضا آنجا هم خودکار اضافه می‌شود پس ننویسش.`
    : `\n\nاین کسب‌وکار ایمیل ندارد: emailSubject و emailBody را null بگذار.`;

  const igBlock = input.igNote
    ? `\nیافته‌ی بررسی دستی پیج اینستاگرام (مشاهده‌ی قطعی): ${input.igNote}`
    : "";

  const prompt = `کسب‌وکار: ${input.businessName}${input.industry ? ` (${input.industry})` : ""}${input.city ? ` — ${input.city}` : ""}
کانال ارسال: ${input.channel ?? "نامشخص"}

خلاصه: ${input.analysis.businessSummary}
مشتری هدفش: ${input.analysis.targetCustomer}
درد اصلی: ${input.analysis.painPoint}
شواهد واقعی (تنها منبع «مشاهده‌ی قطعی»): ${input.analysis.evidence.join(" | ")}
نشانه‌های نیاز: ${input.analysis.needSignals.join("، ")}
لحن مناسب: ${input.analysis.brandTone}${igBlock}

خدمت اصلی انتخاب‌شده‌ی مهدیار: ${serviceLabel}

${pickExamples(input.industry, input.analysis.businessSummary)}

حالا برای این کسب‌وکار پیام اول را بنویس. نمونه‌های بالا فقط برای نشان‌دادن **لحن** هستند؛ از جمله‌هایشان کپی نکن.${emailNote}${
    input.revision
      ? `\n\n— بازنویسی —\nپیام قبلی‌ات این بود:\n«${input.revision.previousMessage}»\n\nمنتقد این ایرادها را گرفت (همه را رفع کن، ولی ساختار و قواعد بالا را نگه دار):\n${input.revision.instructions
          .map((s) => `- ${s}`)
          .join("\n")}`
      : ""
  }`;

  return runAgentJSON({
    agent: AGENT,
    system,
    prompt,
    model: writerModel(),
    temperature: 0.7, // کمی بالاتر از قبل: تنوع لحن لازمه‌ی «قالبی نبودن» است
    maxOutputTokens: 1300,
    schema: MessageWriterOutputSchema,
    shapeHint: `{
  "status": "OK",
  "message": "متن پیام (حدود ${len.min}-${len.max} کلمه)",
  "emailSubject": ${input.hasEmail ? '"موضوع ایمیل"' : "null"},
  "emailBody": ${input.hasEmail ? '"متن ایمیل"' : "null"},
  "observations": ["چیزی که مستقیماً در داده دیده شد"],
  "inferences": ["برداشت غیرقطعی که با زبان محتاطانه در پیام آمده"],
  "servicesUsed": ["${input.serviceId}"],
  "portfolioMention": "available",
  "painTargeted": "دردی که پیام هدف گرفته",
  "cta": "دعوت پایانی",
  "confidence": 0.8
}`,
  });
}
