-- ───────────────────────────────────────────────
-- مهاجرت ۷ — مکان‌نمای کشف (discovery_cursor)
-- در SQL Editor داشبورد Supabase اجرا کنید. idempotent است.
-- ⚠️ این SQL باید **قبل از پوش کد** اجرا شود (قانون دیپلوی پروژه).
-- ───────────────────────────────────────────────
--
-- باگی که این ستون رفع می‌کند:
--
-- مالک «کشف لید» را پشت‌سرهم می‌زد و هر بار ~۲۰ تکراری و ~۰ لید تازه می‌گرفت.
-- علت زنجیره‌ای بود، ولی ریشه‌اش یک چیز: **کمپین هیچ حافظه‌ای از اجرای قبل
-- نداشت**. `runDiscovery(campaignId)` یک تابع خالص از (بازار، شهر، سقف) بود،
-- پس اجرای N+1 هیچ اطلاعی از اجرای N نداشت و دقیقاً همان کار را تکرار می‌کرد:
--
--   • Overpass QL اصلاً OFFSET ندارد؛ `out … N` همیشه N تای اول را به همان
--     ترتیب می‌دهد. یعنی هر اجرا دقیقاً همان مجموعه.
--   • نقشه‌ی جست‌وجوی Tavily ~۶۰ جفت (عبارت، الگو) دارد ولی سقف ۸ فراخوان است،
--     پس فقط plan[0..7] تا امروز اجرا شده بود و جفت‌های ۹ تا ۶۰ هرگز.
--   • مرتب‌سازی پیش از درج به ۸/۰ دودویی («سایت دارد / ندارد») فرو می‌ریخت و با
--     مرتب‌سازی پایدار V8 ترتیب هر اجرا یکسان می‌ماند؛ بعد `slice(0, limit)`
--     **قبل از** بررسی تکراری‌بودن در دیتابیس اجرا می‌شد. یعنی ۲۰ سهمیه‌ی روزانه
--     همیشه صرف همان ۲۰ کسب‌وکارِ از قبل شناخته‌شده می‌شد.
--
-- با این ستون، هر اجرا می‌نویسد «تا کجا رفتم» و اجرای بعدی از همان‌جا ادامه
-- می‌دهد: کاشی بعدی مرز شهر، جفت بعدی نقشه‌ی جست‌وجو، صفحه‌ی بعدی Places.
--
-- چرا jsonb روی خود campaigns و نه یک جدول جدا:
--
--   • رابطه دقیقاً ۱:۱ با کمپین است — هیچ‌وقت دو مکان‌نما برای یک کمپین نداریم.
--   • در هر اجرا یک‌بار خوانده و یک‌بار نوشته می‌شود؛ نه فیلتر می‌شود، نه join،
--     نه گزارش‌گیری روی فیلدهایش. پس ایندکس و ستون‌بندی هیچ سودی نمی‌دهد.
--   • جدول جدا یعنی یک رفت‌وبرگشت اضافه در هر کشف، یک مسیر upsert تازه، و یک
--     شاخه‌ی جدید در آبشار حذف نرمِ مهاجرت ۰۰۶ — همه برای صفر سود.
--   • شکل مکان‌نما هنوز در حال تثبیت است (فیلد `v` برای همین است). تغییر شکل
--     یک jsonb هیچ مهاجرتی نمی‌خواهد؛ تغییر ستون‌های یک جدول می‌خواهد.
--
-- سازگاری: کد بدون این ستون هم کار می‌کند. `getDiscoveryCursor` روی خطای
-- «ستون موجود نیست» مقدار null برمی‌گرداند و کشف پیشرفت را از تعداد اجراهای
-- قبلیِ ثبت‌شده در agent_runs تخمین می‌زند. عمداً `discovery_cursor` به
-- `campaignToRow` اضافه **نشده** تا insert کمپین روی دیتابیسی که این مهاجرت را
-- نخورده نشکند.

alter table campaigns add column if not exists discovery_cursor jsonb;

comment on column campaigns.discovery_cursor is
  'مکان‌نمای پیشرفت کشف لید (jsonb، شکل DiscoveryCursor در src/lib/store/types.ts). '
  'هر اجرای کشف از جایی که اجرای قبل تمام کرده ادامه می‌دهد: کاشی بعدی مرز شهر، '
  'جفت بعدی نقشه‌ی جست‌وجوی وب، صفحه‌ی بعدی Google Places. null یعنی هنوز اجرایی '
  'ثبت نشده. فیلد v نسخه‌ی شکل داده است؛ نسخه‌ی ناشناخته دور ریخته و بازسازی می‌شود.';
